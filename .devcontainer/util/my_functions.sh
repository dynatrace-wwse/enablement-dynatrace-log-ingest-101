# Cluster node reaches Ready.
waitForNodeReady() {
  printInfoSection "Waiting for the cluster node to be Ready"
  local i=0
  while [ "$i" -lt 24 ]; do
    [ "$(kubectl get nodes --no-headers 2>/dev/null | grep -c ' Ready')" -gt 0 ] && { printInfo "node Ready"; return 0; }
    i=$((i + 1)); printInfo "node not Ready yet ($i/24), waiting 5s"; sleep 5
  done
  printError "Cluster node not Ready in time"; return 1
}

# AstroShop demo app has at least one Running pod. AstroShop is heavy and is
# deployed at postCreate, so give it a generous window before failing.
waitForAstroshop() {
  printInfoSection "Waiting for the AstroShop demo app pods to be Running"
  local i=0
  while [ "$i" -lt 48 ]; do
    [ "$(kubectl get pods -n astroshop --no-headers 2>/dev/null | grep -c Running)" -gt 0 ] && { printInfo "AstroShop Running"; return 0; }
    i=$((i + 1)); printInfo "AstroShop not Running yet ($i/48), waiting 10s"; sleep 10
  done
  printError "AstroShop pods not Running in time"; return 1
}

# Dynatrace Operator manager pod reaches Running (Section 4, step 1).
waitForOperatorReady() {
  printInfoSection "Waiting for the Dynatrace Operator pod to be Running"
  local i=0
  while [ "$i" -lt 36 ]; do
    kubectl get pods -n dynatrace --no-headers 2>/dev/null | grep -E 'operator' | grep -q Running && { printInfo "operator Running"; return 0; }
    i=$((i + 1)); printInfo "operator not Running yet ($i/36), waiting 5s"; sleep 5
  done
  printError "Dynatrace Operator pod not Running in time"; return 1
}

# At least two DynaKube custom resources exist (the k8s+log DynaKube and the
# agents DynaKube) - Section 4, step 2.
waitForTwoDynakubes() {
  printInfoSection "Waiting for the two DynaKube custom resources"
  local i=0
  while [ "$i" -lt 30 ]; do
    [ "$(kubectl get dynakube -n dynatrace --no-headers 2>/dev/null | grep -c '')" -gt 1 ] && { printInfo "two DynaKubes present"; return 0; }
    i=$((i + 1)); printInfo "fewer than two DynaKubes yet ($i/30), waiting 5s"; sleep 5
  done
  printError "Two DynaKube custom resources not found in time"; return 1
}

# Log Module (logmonitoring) pod reaches Running (Section 4, step 2).
waitForLogModule() {
  printInfoSection "Waiting for the Dynatrace Log Module (logmonitoring) pod to be Running"
  local i=0
  while [ "$i" -lt 36 ]; do
    kubectl get pods -n dynatrace --no-headers 2>/dev/null | grep logmonitoring | grep -q Running && { printInfo "Log Module Running"; return 0; }
    i=$((i + 1)); printInfo "Log Module not Running yet ($i/36), waiting 10s"; sleep 10
