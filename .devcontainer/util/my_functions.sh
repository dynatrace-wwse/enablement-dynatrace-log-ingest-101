# --- Solution helper: deploy the two DynaKubes the lab teaches ---------
# DynaKube #1 (k8s-only mode) is generated by the framework and includes the
# Log Module (DK_LOG_MONITORING defaults true) scoped to the astroshop
# namespace. DynaKube #2 (agents) adds Application Observability. Together they
# satisfy the "two DynaKubes" and "Log Module Running" checks - the same
# architecture documented in section 4. Assumes the Operator is already
# deployed (dynatraceDeployOperator) and the token secret ($RepositoryName)
# exists.
deployLogIngestDynakubes() {
  printInfoSection "Deploying the Kubernetes+Log Module DynaKube and the Agents DynaKube"

  # DynaKube #1: Kubernetes platform monitoring + Log Module (no OneAgent).
  # k8s-only mode leaves out the oneAgent section; log monitoring is on by default.
  DK_LOG_MONITORING=true deployDynatrace k8s-only

  # Patch DynaKube #1:
  #  - scope the Log Module ingest rule to the astroshop namespace (as the lab teaches);
  #  - DISABLE metadataEnrichment. The framework enables it on #1 with no
  #    namespaceSelector, which makes #1 claim ALL namespaces via the mutating
  #    webhook. The operator then rejects the agents DynaKube #2 with
  #    "tries to inject into namespaces where another Dynakube already injects
  #    into". Turning enrichment off on the k8s/log DynaKube lets the agents
  #    DynaKube own application injection for astroshop.
  # The framework derives the DynaKube name per user (per-user Grail isolation
  # renames it from $RepositoryName), so resolve the ACTUAL DynaKube #1 name —
  # patching the old fixed name silently failed and the webhook then rejected
  # DynaKube #2 with "another Dynakube already injects into these namespaces".
  local dk1
  dk1=$(kubectl get dynakube -n dynatrace -o jsonpath='{.items[0].metadata.name}' 2>/dev/null)
  kubectl -n dynatrace patch dynakube "${dk1:-$RepositoryName}" --type merge \
    -p '{"spec":{"metadataEnrichment":{"enabled":false},"logMonitoring":{"ingestRuleMatchers":[{"attribute":"k8s.namespace.name","values":["astroshop"]}]}}}' \
    || printWarn "Could not patch DynaKube ${dk1:-$RepositoryName} — the agents DynaKube may be rejected"

  # DynaKube #2: Application Observability agents DynaKube. References the same
  # token secret created by dynatraceDeployOperator ($RepositoryName).
  # Constraints learned from the operator's validating webhook:
  #  - DynaKube name must be <= 40 chars (it is the base for resource names), so
  #    use the short name "logingest-agents" (not ${RepositoryName}-agents = 42).
  #  - applicationMonitoring must set a namespaceSelector; the injection selector
  #    lives at spec.oneAgent.applicationMonitoring.namespaceSelector in v1beta6.
  #    Scope it to the astroshop namespace so it does not conflict with #1.
  printInfo "Applying the agents DynaKube (Application Observability, scoped to astroshop)"
  local agents_out
  agents_out=$(kubectl apply -f - 2>&1 <<AGENTS_DK
apiVersion: dynatrace.com/v1beta6
kind: DynaKube
metadata:
  name: logingest-agents
  namespace: dynatrace
spec:
  apiUrl: ${DT_TENANT}/api
  tokens: ${RepositoryName}
  oneAgent:
    applicationMonitoring:
      namespaceSelector:
        matchLabels:
          kubernetes.io/metadata.name: astroshop
  activeGate:
    capabilities:
      - routing
      - debugging
    resources:
      requests:
        cpu: 100m
        memory: 512Mi
      limits:
        cpu: 500m
        memory: 768Mi
    replicas: 1
AGENTS_DK
)
  printInfo "agents DynaKube apply: ${agents_out}"

  printInfo "Both DynaKubes applied. The Operator will reconcile the Log Module and agents."
}