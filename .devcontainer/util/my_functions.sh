# ======================================================================
#   Step-by-step end-to-end verification + solution helpers
# ----------------------------------------------------------------------
#   Called from the lab pages' shell-verification and LAB_SOLUTION blocks.
#   Every Kubernetes/Dynatrace action is asynchronous, so each helper
#   WAITS (bounded retry) for the expected state instead of checking once.
#   This lets the Enablement App (and the app-layer-test driver) verify a
#   step right after the previous one without racing the rollout. Mirrors
#   the Kubernetes 101 golden pattern.
